export function translatePortal(
  lang: LanguageCode | string | undefined,
  key: PortalCopyKey,
  vars?: Record<string, string | number>
): string {
  const code = normalizePortalLang(lang);
  const dict = code === 'am' ? AM_PORTAL : code === 'om' ? OM_PORTAL : EN_PORTAL;
  let text = dict[key] ?? EN_PORTAL[key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
  }
  return text;
}
