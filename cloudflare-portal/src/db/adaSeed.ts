function isoOffsetMonth(monthDelta: number, day: number): string {
  const now = new Date();
  const d = new Date(now.getFullYear(), now.getMonth() + monthDelta, day);
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, '0');
  const dd = String(Math.min(day, 28)).padStart(2, '0');
  return `${y}-${m}-${dd}`;
}

function isoOffsetDaysFromToday(days: number): string {
  const now = new Date();
  const d = new Date(now.getFullYear(), now.getMonth(), now.getDate() + days);
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, '0');
  const dd = String(d.getDate()).padStart(2, '0');
  return `${y}-${m}-${dd}`;
}

